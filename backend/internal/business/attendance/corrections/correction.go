package corrections

import (
	"errors"
	"regexp"
	"strings"
	"time"

	recordmodel "github.com/963sup/line-mini-app-bot/internal/business/attendance/records"
	"github.com/963sup/line-mini-app-bot/internal/business/attendance/worktime"
)

var (
	ErrCorrection          = errors.New("invalid, stale or unauthorized attendance correction")
	ErrIdempotencyConflict = errors.New("idempotency key already used for another correction")
)

var correctionKeyPattern = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

// ValidCorrectionKey accepts the canonical UUID form generated by the Web client.
func ValidCorrectionKey(key string) bool { return correctionKeyPattern.MatchString(key) }

type Correction struct {
	ApplicantName         string
	NewRecord             bool
	ID                    string
	UserKey               string
	GroupID               string
	RecordID              string
	ExpectedEventSequence int64
	ExpectedRevision      int64
	Reason                string
	Start                 time.Time
	End                   time.Time
	Breaks                []worktime.Interval
	RestConfirmed         bool
	CreatedAt             time.Time
}

// CorrectionDetails describes a request and its human decision, never an effective shift.
type CorrectionDetails struct {
	Correction
	Status         string
	DecisionReason string
	ReviewedAt     time.Time
	Before         *recordmodel.Record
}

type CorrectionPage struct {
	Items      []CorrectionDetails
	NextCursor string
}

// ApplyCorrection creates a new projection; original events remain unchanged.
func ApplyCorrection(before recordmodel.Record, c Correction) (recordmodel.Record, error) {
	if c.NewRecord {
		if before.RecordID != "" || !before.ClockInAt.IsZero() || before.Revision != 0 || c.ExpectedRevision != 0 || c.ExpectedEventSequence != 0 {
			return recordmodel.Record{}, ErrCorrection
		}
		before = recordmodel.Record{RecordID: c.RecordID, GroupID: c.GroupID, SchemaVersion: 3}
	}
	if c.RecordID == "" || c.GroupID == "" || c.ExpectedRevision < 0 || c.ExpectedEventSequence < 0 || len(c.Breaks) > 100 || c.ID == "" || c.RecordID != before.RecordID || c.GroupID != before.GroupID || c.ExpectedRevision != before.Revision || c.ExpectedEventSequence != before.EventSequence || strings.TrimSpace(c.Reason) == "" || len(c.Reason) > 2000 || !c.RestConfirmed {
		return recordmodel.Record{}, ErrCorrection
	}
	session := worktime.Session{ID: c.RecordID, Start: c.Start, End: c.End, Breaks: c.Breaks, RestConfirmed: c.RestConfirmed}
	r := worktime.Calculate([]worktime.Session{session}, c.Start, c.End)
	if len(r.Issues) > 0 || c.Start.IsZero() || !c.End.After(c.Start) {
		return recordmodel.Record{}, ErrCorrection
	}
	after := before
	after.ClockInAt, after.ClockOutAt = c.Start, c.End
	after.IsOpen = false
	after.Breaks = append([]worktime.Interval(nil), c.Breaks...)
	after.BreakStartedAt = time.Time{}
	after.RestConfirmed = true
	after.Revision++
	after.CorrectionID = c.ID
	after.LastAppliedAt = c.End
	after.RebuildIssues = nil
	return after, nil
}
