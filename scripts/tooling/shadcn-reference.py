#!/usr/bin/env python3
"""Snapshot official shadcn documentation; never install application components."""

import argparse
import concurrent.futures
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import tempfile
import time
import urllib.error
import urllib.request


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs/development/tooling/frontend/shadcn-reference/snapshot"
ORIGIN = "https://ui.shadcn.com"
BASES = ("base", "radix")
GROUPS = ("components", "ai-elements")


def metadata(text):
    """Read only scalar fields needed from upstream frontmatter, without YAML deps."""
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise ValueError("Expected Markdown frontmatter, received another response")
    fields = {}
    for line in text.split("\n---\n", 1)[0].splitlines()[1:]:
        key, sep, value = line.partition(":")
        if sep:
            fields[key] = value.strip().strip('\"\'')
    if not fields.get("title") or not fields.get("description"):
        raise ValueError("Missing title or description")
    return fields


def discover(group, text):
    # Markdown links and MDX LinkedCard hrefs both occur in the official indexes.
    slugs = sorted(set(re.findall(
        rf"/docs/{group}/(?:(?:base|radix)/)?([a-z0-9]+(?:-[a-z0-9]+)*)(?=[\s\"')#?])",
        text,
    )))
    if not slugs:
        raise ValueError(f"No entries discovered in {group}; upstream format changed")
    return slugs


def fetch(url):
    for attempt in range(3):
        try:
            request = urllib.request.Request(url, headers={"User-Agent": "shadcn-reference-snapshot/1"})
            with urllib.request.urlopen(request, timeout=35) as response:
                body = response.read()
                final_url = response.url
                if not final_url.startswith(ORIGIN + "/"):
                    raise ValueError(f"Unexpected redirect: {final_url}")
                text = body.decode("utf-8")
                fields = metadata(text)
                return body, {
                    "url": url,
                    "resolved_url": final_url,
                    "retrieved_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                    "etag": response.headers.get("ETag"),
                    "last_modified": response.headers.get("Last-Modified"),
                    "sha256": hashlib.sha256(body).hexdigest(),
                    **{key: fields[key] for key in ("title", "description")},
                    "base": fields.get("base"),
                    "deprecated": bool(re.search(r"(?:has been deprecated|is deprecated)", text[:1200], re.I)),
                }
        except (OSError, urllib.error.URLError) as error:
            if attempt == 2:
                raise RuntimeError(f"Cannot fetch {url}: {error}") from error
            time.sleep(attempt + 1)


def render_index(manifest):
    lines = [
        "# shadcn Components 與 AI Elements 本機索引", "",
        "<!-- Generated by scripts/tooling/shadcn-reference.py; do not edit. -->", "",
        f"抓取時間（UTC）：{manifest['retrieved_at']}。", "",
        "這是官方文件與內嵌範例快照，不是已安裝清單；本專案優先讀 Radix。",
        "快照不保證與固定 CLI 同版；使用前仍核對官方 registry。來源及 SHA-256 見 [manifest.json](manifest.json)。", "",
    ]
    records = {entry["path"]: entry for entry in manifest["documents"]}
    for group in GROUPS:
        slugs = manifest["catalog"][group]
        lines += [f"## {group}（{len(slugs)} 項）", "",
                  "| 名稱 | 用途（官方描述） | Radix 文件／範例 | Base UI 文件／範例 | 官方入口 | 注意事項 |",
                  "| --- | --- | --- | --- | --- | --- |"]
        for slug in slugs:
            prefix = f"pages/{group}"
            entry = records[f"{prefix}/radix/{slug}.md"]
            title = entry["title"].replace("|", "\\|").replace("\n", " ")
            description = entry["description"].replace("|", "\\|").replace("\n", " ")
            notes = []
            for base in BASES:
                item = records[f"{prefix}/{base}/{slug}.md"]
                if item["base"] != base:
                    notes.append(f"{base} URL 的 frontmatter 標記為 {item['base']}")
                if item["deprecated"]:
                    notes.append(f"{base} 文件標記已棄用，先讀替代方案")
            lines.append(f"| {title} | {description} | [Radix]({prefix}/radix/{slug}.md) | "
                         f"[Base UI]({prefix}/base/{slug}.md) | [{slug}]({ORIGIN}/docs/{group}/radix/{slug}) | {'；'.join(notes)} |")
        lines.append("")
    return "\n".join(lines)


def check(directory, max_age_days=7):
    manifest = json.loads((directory / "manifest.json").read_text())
    if manifest["schema_version"] != 1:
        raise ValueError("Unsupported snapshot schema")
    records = {entry["path"]: entry for entry in manifest["documents"]}
    if len(records) != len(manifest["documents"]):
        raise ValueError("Duplicate document paths")
    expected = {f"pages/{group}.md" for group in GROUPS}
    for group in GROUPS:
        root_text = (directory / f"pages/{group}.md").read_text()
        slugs = discover(group, root_text)
        if slugs != manifest["catalog"][group]:
            raise ValueError(f"Catalog does not match captured {group} index")
        expected.update(f"pages/{group}/{base}/{slug}.md" for slug in slugs for base in BASES)
    if set(records) != expected:
        raise ValueError("Snapshot is missing required documents or contains unexpected entries")
    actual = {str(path.relative_to(directory)) for path in (directory / "pages").rglob("*") if path.is_file()}
    if actual != expected:
        raise ValueError("Files do not match manifest")
    for path, entry in records.items():
        body = (directory / path).read_bytes()
        if hashlib.sha256(body).hexdigest() != entry["sha256"]:
            raise ValueError(f"Hash mismatch: {path}")
        fields = metadata(body.decode("utf-8"))
        if entry["base"] != fields.get("base"):
            raise ValueError(f"Recorded base does not match upstream: {path}")
        deprecated = bool(re.search(r"(?:has been deprecated|is deprecated)", body.decode("utf-8")[:1200], re.I))
        if entry["deprecated"] != deprecated:
            raise ValueError(f"Deprecation marker mismatch: {path}")
        if entry["url"] != ORIGIN + "/docs/" + path.removeprefix("pages/"):
            raise ValueError(f"Unexpected source URL: {path}")
        if any(entry[key] != fields[key] for key in ("title", "description")):
            raise ValueError(f"Metadata mismatch: {path}")
    if (directory / "INDEX.md").read_text() != render_index(manifest):
        raise ValueError("Generated index does not match manifest")
    age = (datetime.now(timezone.utc) - datetime.fromisoformat(manifest["retrieved_at"])).total_seconds() / 86400
    if not 0 <= age <= max_age_days:
        raise ValueError(f"Snapshot age {age:.1f} days exceeds {max_age_days}; refresh it")
    counts = ", ".join(f"{group}={len(manifest['catalog'][group])}" for group in GROUPS)
    print(f"PASS: {counts}; {len(records)} documents; hashes, coverage, bases, index and freshness")


def refresh():
    documents = {}
    catalog = {}
    for group in GROUPS:
        path = f"pages/{group}.md"
        documents[path] = fetch(f"{ORIGIN}/docs/{group}.md")
        catalog[group] = discover(group, documents[path][0].decode("utf-8"))
    paths = [f"pages/{group}/{base}/{slug}.md"
             for group in GROUPS for slug in catalog[group] for base in BASES]
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as executor:
        pending = {executor.submit(fetch, ORIGIN + "/docs/" + path.removeprefix("pages/")): path
                   for path in paths}
        for count, future in enumerate(concurrent.futures.as_completed(pending), 1):
            documents[pending[future]] = future.result()
            if count % 20 == 0 or count == len(paths):
                print(f"Downloaded {count}/{len(paths)} component/pattern documents", flush=True)
    # Re-read entry points: a moving catalog must not produce a silently incomplete snapshot.
    for group in GROUPS:
        latest, _ = fetch(f"{ORIGIN}/docs/{group}.md")
        if discover(group, latest.decode("utf-8")) != catalog[group]:
            raise ValueError(f"{group} changed during refresh; retry")
    manifest = {
        "schema_version": 1,
        "retrieved_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "source_kind": "live official Markdown; timestamps and hashes, not an immutable Git revision",
        "catalog": catalog,
        "documents": [{"path": path, **entry} for path, (_, entry) in sorted(documents.items())],
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    # Validate a complete staging directory before replacing the previous snapshot.
    with tempfile.TemporaryDirectory(prefix=".shadcn-reference-", dir=OUTPUT.parent) as temporary:
        stage = Path(temporary) / "snapshot"
        stage.mkdir()
        for path, (body, _) in documents.items():
            target = stage / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(body)
        (stage / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
        (stage / "INDEX.md").write_text(render_index(manifest))
        check(stage)
        previous = Path(temporary) / "previous"
        if OUTPUT.exists():
            OUTPUT.rename(previous)
        try:
            stage.rename(OUTPUT)
        except OSError:
            if previous.exists():
                previous.rename(OUTPUT)
            raise
    print(f"Saved {OUTPUT}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify local snapshot without network or writes")
    parser.add_argument("--max-age-days", type=int, default=7, help="Maximum snapshot age for --check (default: 7)")
    args = parser.parse_args()
    try:
        if args.check:
            check(OUTPUT, args.max_age_days)
        else:
            refresh()
    except (OSError, ValueError, KeyError, RuntimeError) as error:
        parser.exit(1, f"shadcn reference: {error}\n")


if __name__ == "__main__":
    main()
